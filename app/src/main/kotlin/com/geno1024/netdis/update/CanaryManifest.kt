package com.geno1024.netdis.update

/**
 * Metadata for the rolling canary build, published next to the APK as a
 * `canary.properties` asset.
 *
 * Flat `key=value` rather than JSON: every value is a simple token, so the
 * format stays parseable by the JVM unit tests without a serialization
 * dependency.
 */
data class CanaryInfo(
    val runNumber: Int,
    val versionName: String,
    val sizeBytes: Long,
    val sha256: String,
    val assetName: String,
) {
    val shortSha: String get() = sha256.take(8)
}

object CanaryManifest {

    const val ASSET_NAME = "canary.properties"

    /** Used when a manifest omits assetName or carries an unusable one. */
    const val FALLBACK_ASSET_NAME = "app-release.apk"

    const val REPO = "Geno1024-AIGC/netdis-android"

    private const val TAG = "canary"

    /** Direct GitHub URL for the manifest. Small enough for a slow link. */
    val DIRECT_URL: String = "https://github.com/$REPO/releases/download/$TAG/$ASSET_NAME"

    /**
     * The asset comes from the manifest rather than being fixed here, so that
     * renaming what CI publishes does not silently leave the app fetching a
     * stale file.
     */
    fun apkUrl(assetName: String): String =
        "https://github.com/$REPO/releases/download/$TAG/${safeAssetName(assetName)}"

    /** A release asset name is one path segment, so it is validated, not trusted. */
    private fun safeAssetName(name: String): String {
        val candidate = name.trim()
        val ascii = candidate.all {
            it in 'a'..'z' || it in 'A'..'Z' || it in '0'..'9' ||
                it == '.' || it == '_' || it == '-'
        }
        val valid = candidate.isNotEmpty() &&
            candidate.length <= 128 &&
            candidate.endsWith(".apk", ignoreCase = true) &&
            ascii
        return if (valid) candidate else FALLBACK_ASSET_NAME
    }

    /**
     * The canary channel is ordered by CI run number. `versionCode` carries it
     * on a CI build, but a local build uses the commit count there instead, so
     * read the env segment of `0.1.<env>.<pack>.<sha8>` first and only fall
     * back to `versionCode` when the name does not have that shape.
     */
    fun installedRunNumber(versionName: String, versionCode: Int): Int {
        val parts = versionName.trim().split('.')
        val env = if (parts.size >= 3 && parts[0] == "0" && parts[1] == "1") {
            parts[2].toIntOrNull()
        } else {
            null
        }
        return env ?: versionCode
    }

    fun parse(text: String): CanaryInfo? {
        val values = HashMap<String, String>()
        for (rawLine in text.lineSequence()) {
            val line = rawLine.trim()
            if (line.isEmpty() || line.startsWith("#") || line.startsWith("!")) continue
            val separator = line.indexOf('=')
            if (separator <= 0) continue
            values[line.substring(0, separator).trim()] = line.substring(separator + 1).trim()
        }
        val runNumber = values["runNumber"]?.toIntOrNull() ?: return null
        val sha256 = values["sha256"]?.lowercase()?.takeIf { it.length == 64 }
            ?.takeIf { it.all { c -> c in '0'..'9' || c in 'a'..'f' } }
            ?: return null
        return CanaryInfo(
            runNumber = runNumber,
            versionName = values["versionName"].orEmpty().ifEmpty { "canary" },
            sizeBytes = values["sizeBytes"]?.toLongOrNull() ?: 0L,
            sha256 = sha256,
            assetName = values["assetName"].orEmpty().ifEmpty { FALLBACK_ASSET_NAME },
        )
    }

    /** Renders the manifest CI uploads; used by the tests and the workflow. */
    fun render(info: CanaryInfo, commit: String): String = buildString {
        appendLine("# Generated by the Build workflow. Consumed by the in-app updater.")
        appendLine("runNumber=${info.runNumber}")
        appendLine("versionName=${info.versionName}")
        appendLine("sizeBytes=${info.sizeBytes}")
        appendLine("sha256=${info.sha256}")
        appendLine("assetName=${info.assetName}")
        appendLine("commit=$commit")
    }
}
